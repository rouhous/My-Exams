const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/grade11/core/units/paper-b-preview.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!document.querySelector('#start').disabled,{timeout:30000});
 if(!(await page.locator('#ready').textContent()).includes('2 / 2'))throw Error('Listening MP3 count not verified at runtime');
 await page.click('#start');
 if(await page.locator('section.part').count()!==9)throw Error('Missing official nine sections');
 if(await page.locator('.q').count()!==45)throw Error('Required 45 exam questions not present');
 if(await page.locator('textarea').count()!==2)throw Error('Both writing activities missing');
 if(!(await page.locator('#paperMarks').textContent()).includes('60 marks'))throw Error('Total marks not 70');
 if(!(await page.locator('#clock').textContent()).startsWith('02:'))throw Error('150-minute timer absent');
 if(await page.locator('section.part audio').count()!==2)throw Error('Listening players not linked');
 await page.click('#end');
 if(!(await page.locator('#results').textContent()).includes('0 / 37'))throw Error('Incorrect automatic objective count');
 if(!(await page.locator('#results').textContent()).includes('8 short answers'))throw Error('Short answers were silently auto-graded');
 await page.click('#back');
 await page.selectOption('#mode','skill');
 await page.selectOption('#skill','rdg3');
 await page.click('#start');
 if(await page.locator('section.part').count()!==1)throw Error('Independent skill must have one section');
 if(await page.locator('.q').count()!==8)throw Error('Reading 3 must have ten questions');
 if(!(await page.locator('#clock').isHidden()))throw Error('Independent skill must not have timer');
 if(errors.length)throw Error('Browser page errors: '+errors.join(' | '));
 console.log('PASS: 9 sections, 60 marks, MP3 2/2, 50 questions, honest grading, 150-minute exam, untimed skill');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
